/**
 * Structural guards.
 *
 * The route handlers and the admin page cannot be imported here (they pull in
 * next/server, mongoose and React), so we assert on their source instead. Each
 * guard corresponds to a bug that shipped to main.
 */
function readRepoFile(relativePath: string): string {
  return readFileSync(new URL(`../../${relativePath}`, import.meta.url), "utf8");
}

function stripComments(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");
}

