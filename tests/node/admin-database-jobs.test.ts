describe("parseRetentionDays", () => {
  it("defaults to 90 days when nothing is provided", () => {
    for (const value of [undefined, null, ""]) {
      const result = parseRetentionDays(value);
      assert.equal(result.ok, true);
      assert.equal(result.days, DEFAULT_RETENTION_DAYS);
    }
  });

  it("keeps an explicit value of 1 instead of falling back to the default", () => {
    const result = parseRetentionDays(1);
    assert.equal(result.ok, true);
    assert.equal(result.days, 1);
  });

  it("accepts numeric strings from the query string", () => {
    const result = parseRetentionDays("45");
    assert.equal(result.ok, true);
    assert.equal(result.days, 45);
  });

  it("rejects a zero or negative retention window (would expire every job)", () => {
    for (const value of [0, -1, -90]) {
      const result = parseRetentionDays(value);
      assert.equal(result.ok, false, String(value));
      assert.match(String(result.error), /between 1 and 3650/);
      assert.equal(result.days, DEFAULT_RETENTION_DAYS);
    }
  });

  it("rejects non-integer, non-numeric and absurdly large values", () => {
    for (const value of ["abc", "12abc", 1.5, Number.NaN, Number.POSITIVE_INFINITY, true, {}, MAX_RETENTION_DAYS + 1]) {
      const result = parseRetentionDays(value);
      assert.equal(result.ok, false, JSON.stringify(value));
    }
  });

  it("accepts the maximum retention window", () => {
    const result = parseRetentionDays(MAX_RETENTION_DAYS);
    assert.equal(result.ok, true);
    assert.equal(result.days, MAX_RETENTION_DAYS);
  });
});

