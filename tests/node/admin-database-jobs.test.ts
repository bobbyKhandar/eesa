describe("planRestore", () => {
  it("includes every managed collection even when the backup predates it", () => {
    const plan = planRestore({ questions: [{ _id: 1 }] }, MANAGED_COLLECTION_NAMES);
    assert.equal(plan.length, MANAGED_COLLECTION_NAMES.length);
    assert.deepEqual(
      plan.map((entry) => entry.name),
      [...MANAGED_COLLECTION_NAMES]
    );
  });

  it("clears examAttempts when an older backup omits them", () => {
    const plan = planRestore({ questions: [{ _id: 1 }] }, MANAGED_COLLECTION_NAMES);
    const attempts = plan.find((entry) => entry.name === "examAttempts");
    assert.ok(attempts);
    assert.equal(attempts!.presentInBackup, false);
    assert.deepEqual(attempts!.docs, []);
  });

  it("marks collections missing from the payload so they are still cleared", () => {
    const plan = planRestore({ questions: [{ _id: 1 }] }, MANAGED_COLLECTION_NAMES);
    const subject = plan.find((entry) => entry.name === "Subject");
    assert.ok(subject);
    assert.equal(subject!.presentInBackup, false);
    assert.deepEqual(subject!.docs, []);
  });

  it("keeps documents for collections that are present", () => {
    const plan = planRestore({ Subject: [{ name: "Maths" }] }, MANAGED_COLLECTION_NAMES);
    const subject = plan.find((entry) => entry.name === "Subject")!;
    assert.equal(subject.presentInBackup, true);
    assert.equal(subject.docs.length, 1);
  });

  it("treats a corrupt payload as empty instead of throwing", () => {
    for (const payload of [null, undefined, "not-an-object", 42, [1, 2, 3]]) {
      const plan = planRestore(payload, MANAGED_COLLECTION_NAMES);
      assert.equal(plan.length, MANAGED_COLLECTION_NAMES.length);
      assert.ok(plan.every((entry) => entry.docs.length === 0));
      assert.ok(plan.every((entry) => entry.presentInBackup === false));
    }
  });

  it("ignores collections that are not managed", () => {
    const plan = planRestore({ auditLog: [{ _id: 1 }] }, MANAGED_COLLECTION_NAMES);
    assert.ok(!plan.some((entry) => entry.name === "auditLog"));
  });
});

describe("chunkDocuments", () => {
  it("splits documents into batches without losing or duplicating any", () => {
    const docs = Array.from({ length: 250 }, (_, index) => ({ index }));
    const batches = chunkDocuments(docs, 100);
    assert.deepEqual(
      batches.map((batch) => batch.length),
      [100, 100, 50]
    );
    assert.deepEqual(batches.flat(), docs);
  });

  it("returns no batches for empty input", () => {
    assert.deepEqual(chunkDocuments([], 100), []);
    assert.deepEqual(chunkDocuments(undefined as any, 100), []);
  });

  it("falls back to the default batch size for invalid values", () => {
    const docs = Array.from({ length: RESTORE_BATCH_SIZE + 5 }, (_, index) => index);
    for (const size of [0, -10, Number.NaN, Number.POSITIVE_INFINITY]) {
      const batches = chunkDocuments(docs, size);
      assert.deepEqual(
        batches.map((batch) => batch.length),
        [RESTORE_BATCH_SIZE, 5]
      );
    }
  });
});

