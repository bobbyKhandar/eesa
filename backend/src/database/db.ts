/**
 * Submit exam (finalize submission)
 */
export async function finalizeExamSubmission(
  submissionId: string,
  autoSubmitted: boolean = false
): Promise<{ success: boolean; error?: string }> {
  try {
    await connect();

    const result = await ExamSubmissionModel.updateOne(
      { _id: submissionId },
      {
        $set: {
          status: 'SUBMITTED',
          submittedAt: new Date(),
          autoSubmitted
        }
      }
    );

    if (result.matchedCount === 0) {
      return { success: false, error: 'Submission not found' };
    }

    // Move exam from currentAllocatedExams to submissionHistory
    const submission = await ExamSubmissionModel.findById(submissionId).select('userId examId');
    if (submission) {
      await UserModel.updateOne(
        { _id: submission.userId },
        {
          $pull: { currentAllocatedExams: submission.examId },
          $addToSet: { submissionHistory: submissionId }
        }
      );
    }

    return { success: true };
  } catch (error) {
    console.error('Error finalizing exam submission:', error);
    return { success: false, error: 'Failed to finalize exam submission' };
  }
}

/**
 * Evaluate exam submission (grade and provide feedback)
 */
export async function evaluateExamSubmission(
  submissionId: string,
  evaluation: {
    totalScore: number;
    responses: Array<{
      examQuestionId: string;
      allottedMarks: number;
      feedback?: string;
    }>;
  }
): Promise<{ success: boolean; error?: string }> {
  try {
    await connect();

    const submission = await ExamSubmissionModel.findById(submissionId);
    if (!submission) {
      return { success: false, error: 'Submission not found' };
    }

    // Update responses with marks and feedback
    const updatedResponses = submission.responses.map(response => {
      const evalResponse = evaluation.responses.find(
        er => er.examQuestionId === response.examQuestionId
      );
      return {
        ...response,
        allottedMarks: evalResponse?.allottedMarks ?? 0,
        feedback: evalResponse?.feedback
      };
    });

    await ExamSubmissionModel.updateOne(
      { _id: submissionId },
      {
        $set: {
          status: 'EVALUATED',
          evaluatedAt: new Date(),
          totalScore: evaluation.totalScore,
          responses: updatedResponses
        }
      }
    );

    return { success: true };
  } catch (error) {
    console.error('Error evaluating exam submission:', error);
    return { success: false, error: 'Failed to evaluate exam submission' };
  }
}
