/**
 * Creates an exam together with its questions.
 * All parameters must already be validated by the caller.
 */
export async function createExam(
  examTitle: string,
  examDescription: string,
  examType: string,
  examMaxMarks: number,
  passingPercentage: number,
  examDegree: string,
  examUsers: string[], // Array of user emails
  clientQuestions: ClientQuestion[]
) {
  // Validate client questions using Zod schema before inserting
  const questionsValidation = clientQuestions.map((question, index) => {
    const result = clientQuestionZodSchema.safeParse(question);
    if (!result.success) {
      throw new Error(`Question ${index + 1} validation failed: ${result.error.message}`);
    }
    return result.data;
  });

  await connect(); // throws if connection fails

  const inserted = await QuestionModel.insertMany(questionsValidation);
  const questionsForExam = inserted.map((doc, i) => ({
    questionId: doc._id.toString(),
    marks: clientQuestions[i].marks
  }));

  /* ----------------------- EXAM ------------------------- */
  const exam = new ExamModel({
    examTitle,
    examDescription,
    examType,
    examMaxMarks,
    passingPercentage,
    examDegree,
    questions: questionsForExam // <-- property name per examZodSchema
  });

  const savedExam = await exam.save();

  // Update the users with the new exam
  await UserModel.updateMany(
    { email: { $in: examUsers } }, // Find users by email
    { $push: { currentAllocatedExams: savedExam._id } } // Push the exam ID to their currentAllocatedExams array
  );

  // keep global connection open; server manages lifecycle
  return savedExam;
}
// Internal helper that returns full exam details for a user by kind
export async function getUserExams(email: string, kind: 'allocated' | 'submitted'): Promise<GetUserExamsResponse> {
  try {
    await connect();
    
    // Pull both fields to avoid a second query when switching kinds
    const user = await UserModel.findOne(
      { email }, 
      { currentAllocatedExams: 1, submittedExams: 1, _id: 0 }
    ).lean();
    
    if (!user) {
      return { error: 'No user found with that email' };
    }
    
    const rawIds = kind === 'allocated'
      ? (user.currentAllocatedExams || [])
      : (user.submittedExams || []);
    
    const examIds = rawIds.map((id: any) => id?.toString?.() ?? String(id));
    
    if (examIds.length === 0) {
      return { exams: [] };
    }
    
    // Convert string IDs to ObjectIds and fetch full exam docs
    const objectIds = examIds.map(id => Types.ObjectId.createFromHexString(id));
    const exams = await ExamModel.find({ _id: { $in: objectIds } }, { __v: 0 });
    
    const transformedExams: TransformedExam[] = exams.map(exam => ({
      id: exam._id.toString(),
      _id: exam._id.toString(),
      title: exam.examTitle,
      description: exam.examDescription,
      questions: exam.questions?.length || 0,
      duration: 60, // default placeholder
      status: 'active', // default placeholder
      createdAt: new Date().toISOString(), // placeholder
      submissions: 0 // placeholder
    }));
    
    return { exams: transformedExams };
  } catch (err) {
    console.log('Error in getUserExams:', err);
    return { error: 'Failed to retrieve exams for user' };
  }
}

export async function getQuestions(examSetId: string) {
  await connect();
  try {
    // Convert examSetId string to ObjectId
    const examSetObjectId = Types.ObjectId.createFromHexString(examSetId);
    console.log("Exam Set ObjectId:", examSetObjectId);

    const ExamId = await ExamModel.find({ _id: examSetObjectId }, { _id: 0, __v: 0 });
    console.log(ExamId);

    if (!ExamId || ExamId.length === 0) {
      console.log("No exam found with the provided ID");
      return [];
    }

    const questionIds = ExamId[0].questions.map((q: any) => {
      if (q.questionId instanceof Types.ObjectId) {
        return q.questionId;
      } else {
        return Types.ObjectId.createFromHexString(q.questionId);
      }
    });

    const results = await QuestionModel.find(
      { _id: { $in: questionIds } },
      { _id: 1, text: 1, answer: 1, options: 1, type: 1 }
    ).lean();

    const marksMap: Record<string, number> = {};
    ExamId[0].questions.forEach((q: any) => {
      marksMap[q.questionId.toString()] = q.marks;
    });

    // Create new array with marks instead of mutating
    const questionsWithMarks = results.map((question: any) => {
      const idStr = question._id.toString();
      return {
        _id: idStr, // Keep the ID as string for frontend
        text: question.text,
        answer: question.answer || 'NOT PRESENT',
        options: question.options || [],
        type: question.type,
        marks: marksMap[idStr] || 1, // Default to 1 mark if not found
      };
    });

    console.log("Fetched Questions with marks:", questionsWithMarks);
    return questionsWithMarks;
  } catch (error) {
    console.error("Error fetching questions:", error);
    return [];
  }
}

