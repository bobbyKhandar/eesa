/**
 * Submit exam answers and trigger evaluation
 */
export async function submitExam(
  examId: string,
  studentEmail: string,
  answers: Record<string, string>,
  timeSpent: number,
  autoSubmitted: boolean = false
): Promise<SubmitExamResponse> {
  // Validate input using Zod schema
  const validationResult = submitExamRequestZodSchema.safeParse({
    examId,
    studentEmail,
    answers,
    timeSpent,
    autoSubmitted
  });
  
  if (!validationResult.success) {
    return { 
      success: false, 
      error: `Validation failed: ${validationResult.error.message}` 
    };
  }
  try {
    await connect();

    // Check if submission already exists
    const existingSubmission = await ExamSubmissionModel.findOne({
      examId,
      studentEmail
    });

    if (existingSubmission) {
      await disconnect();
      return { success: false, error: 'Exam already submitted' };
    }

    // Get student name from user model and exam title
    const [user, examDoc] = await Promise.all([
      UserModel.findOne({ email: studentEmail }),
      ExamModel.findById(examId).select({ examTitle: 1 })
    ]);

    const studentName = studentEmail.split('@')[0]; // Fallback to email prefix
    const examTitle = examDoc?.examTitle || 'Exam';

    // Create submission record
    const submission = new ExamSubmissionModel({
      examId,
      examTitle,
      studentEmail,
      studentName,
      answers,
      timeSpent,
      autoSubmitted,
      submittedAt: new Date()
    });

    const savedSubmission = await submission.save();
    console.log('Exam submission saved:', savedSubmission._id);

    // Trigger async evaluation and email (evaluation function handles its own connect/disconnect)
    evaluateAndEmailResults(savedSubmission._id.toString(), examId, answers)
      .catch(error => console.error('Error in async evaluation:', error));

    // Do not disconnect here to prevent racing with evaluation; callers manage connection lifecycle per request
    return { success: true, submissionId: savedSubmission._id.toString() };
  } catch (error) {
    console.error('Error submitting exam:', error);
    // Keep connection state unchanged here; caller/evaluator manages disconnects
    return { success: false, error: 'Failed to submit exam' };
  }
}

